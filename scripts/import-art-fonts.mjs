/**
 * Import local handwriting fonts as "art" signature bases.
 *
 * Usage: node scripts/import-art-fonts.mjs "<source folder>"
 *
 * Skips fonts whose filename marks them as license-restricted
 * (demo / personal use / free / dafont / trial) and fonts missing
 * A-Z or a-z glyph coverage. Idempotent — regenerates all outputs.
 *
 * Outputs:
 *   public/fonts/art/<slug>.(ttf|otf)  — copied font files
 *   public/fonts/art-fonts.css         — @font-face sheet
 *   src/lib/art-font-bases.ts          — ART_FONT_BASES catalog
 */
import fs from "node:fs";
import path from "node:path";
import * as fontkit from "fontkit";

const projectRoot = process.cwd();
const sourceDir = process.argv[2];
if (!sourceDir || !fs.existsSync(sourceDir)) {
  console.error("Usage: node scripts/import-art-fonts.mjs \"<source folder>\"");
  process.exit(1);
}

const RESTRICTED = /demo|personal|free|dafont|trial/i;
const fontsOutDir = path.join(projectRoot, "public", "fonts", "art");
const cssOutFile = path.join(projectRoot, "public", "fonts", "art-fonts.css");
const tsOutFile = path.join(projectRoot, "src", "lib", "art-font-bases.ts");

function cleanName(fileName) {
  let name = fileName.replace(/(\.(ttf|otf))+$/i, "");
  name = name.replace(/[_]+/g, " ").replace(/\s+/g, " ").trim();
  return name;
}

function slugify(name) {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function hasAlphabetCoverage(font) {
  const missing = [];
  for (let c = 0x41; c <= 0x5a; c++) {
    if (!font.hasGlyphForCodePoint(c)) missing.push(String.fromCharCode(c));
  }
  for (let c = 0x61; c <= 0x7a; c++) {
    if (!font.hasGlyphForCodePoint(c)) missing.push(String.fromCharCode(c));
  }
  return missing;
}

const files = fs
  .readdirSync(sourceDir)
  .filter((f) => /\.(ttf|otf)(\.(ttf|otf))*$/i.test(f))
  .sort((a, b) => a.localeCompare(b, "en", { sensitivity: "base" }));

const skipped = { restricted: [], parseError: [], missingGlyphs: [], duplicate: [] };
const accepted = [];
const seenSlugs = new Set();

for (const file of files) {
  if (RESTRICTED.test(file)) {
    skipped.restricted.push(file);
    continue;
  }
  const name = cleanName(file);
  const slug = slugify(name);
  if (seenSlugs.has(slug)) {
    skipped.duplicate.push(file);
    continue;
  }
  const srcPath = path.join(sourceDir, file);
  let font;
  try {
    font = fontkit.openSync(srcPath);
    // Collections: take the first font.
    if (font.fonts) font = font.fonts[0];
  } catch (err) {
    skipped.parseError.push(`${file} (${err.message})`);
    continue;
  }
  const missing = hasAlphabetCoverage(font);
  if (missing.length > 0) {
    skipped.missingGlyphs.push(`${file} (missing: ${missing.join("")})`);
    continue;
  }
  const ext = file.toLowerCase().endsWith(".otf") ? "otf" : "ttf";
  seenSlugs.add(slug);
  accepted.push({ file, name, slug, ext, srcPath });
}

fs.rmSync(fontsOutDir, { recursive: true, force: true });
fs.mkdirSync(fontsOutDir, { recursive: true });
for (const f of accepted) {
  fs.copyFileSync(f.srcPath, path.join(fontsOutDir, `${f.slug}.${f.ext}`));
}

const css = [
  "/* Generated by scripts/import-art-fonts.mjs — do not edit by hand. */",
  ...accepted.map((f) =>
    [
      "@font-face {",
      `  font-family: "Art ${f.name}";`,
      `  src: url("/fonts/art/${f.slug}.${f.ext}") format("${f.ext === "otf" ? "opentype" : "truetype"}");`,
      "  font-display: swap;",
      "}",
    ].join("\n"),
  ),
].join("\n\n") + "\n";
fs.writeFileSync(cssOutFile, css);

const ts = `// Generated by scripts/import-art-fonts.mjs — do not edit by hand.
// ${accepted.length} local handwriting fonts served from /fonts/art/ via
// public/fonts/art-fonts.css. All premium (1 credit unlock), category "art".
import type { ArtistBase } from "@/lib/signature-bases";

const ART_DEFAULTS: ArtistBase["defaults"] = {
  fluidity: 80,
  rhythm: 60,
  pressure: 50,
  slant: 6,
  size: 1.05,
};

function artBase(slug: string, name: string): ArtistBase {
  return {
    id: \`art-\${slug}\`,
    name,
    blurb: "Handwritten art font",
    fontFamily: \`"Art \${name}", cursive\`,
    tier: "premium",
    category: "art",
    source: "local",
    defaults: ART_DEFAULTS,
    previewClass: \`font-sig-art-\${slug}\`,
  };
}

export const ART_FONT_BASES: readonly ArtistBase[] = [
${accepted.map((f) => `  artBase(${JSON.stringify(f.slug)}, ${JSON.stringify(f.name)}),`).join("\n")}
];
`;
fs.writeFileSync(tsOutFile, ts);

console.log(`Accepted: ${accepted.length} fonts -> public/fonts/art/`);
const totalBytes = accepted.reduce(
  (sum, f) => sum + fs.statSync(path.join(fontsOutDir, `${f.slug}.${f.ext}`)).size,
  0,
);
console.log(`Total size: ${(totalBytes / 1024 / 1024).toFixed(1)} MB`);
for (const [reason, list] of Object.entries(skipped)) {
  if (!list.length) continue;
  console.log(`\nSkipped (${reason}): ${list.length}`);
  for (const item of list) console.log(`  - ${item}`);
}
